"""Builds TardisPhaseCurves.java from the TARDIS take-off and landing sounds.

The exterior fades in and out in time with the wheeze: the sound's pitch wobble (spectral centroid,
detrended) drives the pulses, and an overall fade carries the box from solid to gone (take-off) or
gone to solid (landing). One value per game tick. Re-run after changing type70demat.ogg / type70mat.ogg:

    python3 tools/tardis/phase_curves.py
"""
import os
import subprocess

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SOUNDS = os.path.join(ROOT, 'src/main/resources/assets/gallifrey/sounds')
OUT = os.path.join(ROOT, 'src/main/java/com/cerulixteam/gallifrey/tardis/TardisPhaseCurves.java')
SR = 8000
TICK = SR // 20  # samples per game tick

# Timings in seconds, picked by ear against the sounds.
DEMAT_FADE_START, DEMAT_GONE = 2.5, 23.5     # box starts pulsing / is fully gone
DEMAT_TICKS = 480                            # 24 s: then the TARDIS is in the vortex (sound tail plays on)
REMAT_APPEAR, REMAT_SOLID = 4.0, 18.6        # first faint pulse / the final landing thud
REMAT_TICKS = 400                            # 20 s


def load(name):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', os.path.join(SOUNDS, name), '-ac', '1', '-ar', str(SR),
                          '-f', 's16le', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.int16).astype(float) / 32768


def wheeze(audio, ticks):
    """0..1 per tick: the rise and fall of the wheeze (1 = the 'out' part of each breath)."""
    cent = []
    for i in range(ticks):
        seg = audio[i * TICK:i * TICK + TICK * 3]
        if len(seg) < 256 or np.abs(seg).max() < 1e-4:
            cent.append(np.nan)
            continue
        s = np.abs(np.fft.rfft(seg * np.hanning(len(seg))))
        f = np.fft.rfftfreq(len(seg), 1 / SR)
        cent.append((s * f).sum() / (s.sum() + 1e-9))
    c = np.array(cent)
    c[np.isnan(c)] = np.nanmean(c)
    c = np.convolve(c, np.ones(5) / 5, 'same')                 # smooth (0.25 s)
    trend = np.convolve(c, np.ones(40) / 40, 'same')          # remove slow drift (2 s)
    d = c - trend
    sd = np.sqrt(np.convolve(d ** 2, np.ones(60) / 60, 'same')) + 1e-6
    return 0.5 + 0.5 * np.tanh(1.4 * d / sd)


def smooth(x):
    x = np.clip(x, 0, 1)
    return x * x * (3 - 2 * x)


def build():
    t_d = np.arange(DEMAT_TICKS + 1) / 20
    w_d = wheeze(load('type70demat.ogg'), DEMAT_TICKS + 1)
    u = np.clip((t_d - DEMAT_FADE_START) / (DEMAT_GONE - DEMAT_FADE_START), 0, 1)
    peak = (1 - u) ** 1.15
    depth = 0.9 * smooth(u * 4)                               # pulses get deeper as it goes
    demat = np.where(t_d < DEMAT_FADE_START, 1.0, peak * (1 - depth * w_d))
    demat[t_d >= DEMAT_GONE] = 0
    lamp_d = np.where(t_d < 1.0, 1.0, 1 - 0.85 * w_d)

    t_r = np.arange(REMAT_TICKS + 1) / 20
    w_r = wheeze(load('type70mat.ogg'), REMAT_TICKS + 1)
    u = np.clip((t_r - REMAT_APPEAR) / (REMAT_SOLID - REMAT_APPEAR), 0, 1)
    peak = u ** 1.3
    depth = 0.9 * smooth((1 - u) * 4)
    remat = peak * (1 - depth * w_r)
    remat[t_r >= REMAT_SOLID] = 1
    lamp_r = np.where(t_r >= REMAT_SOLID, 1.0, 1 - 0.85 * w_r)
    return demat, lamp_d, remat, lamp_r


def arr(name, a):
    vals = ', '.join('%.3ff' % v for v in a)
    return '    static final float[] %s = {%s};\n' % (name, vals)


def main():
    demat, lamp_d, remat, lamp_r = build()
    java = '''package com.cerulixteam.gallifrey.tardis;

/**
 * How visible the TARDIS exterior is on each tick of take-off and landing, and how bright its lamp is.
 * GENERATED by tools/tardis/phase_curves.py from type70demat.ogg and type70mat.ogg so the box fades in
 * and out in time with the sound. Re-run the script rather than editing these numbers.
 */
public final class TardisPhaseCurves {
    private TardisPhaseCurves() {}

    /** Take-off length in ticks. After this the TARDIS is in the vortex. */
    public static final int DEMAT_TICKS = %d;
    /** Landing length in ticks. */
    public static final int REMAT_TICKS = %d;

%s%s%s%s
    /** Exterior opacity (0 = gone, 1 = solid) at a point in take-off, between ticks. */
    public static float dematAlpha(float ticks) { return sample(DEMAT_ALPHA, ticks); }
    public static float dematLamp(float ticks) { return sample(DEMAT_LAMP, ticks); }
    /** Exterior opacity at a point in landing, between ticks. */
    public static float rematAlpha(float ticks) { return sample(REMAT_ALPHA, ticks); }
    public static float rematLamp(float ticks) { return sample(REMAT_LAMP, ticks); }

    private static float sample(float[] curve, float ticks) {
        if (ticks <= 0) return curve[0];
        if (ticks >= curve.length - 1) return curve[curve.length - 1];
        int i = (int) ticks;
        float f = ticks - i;
        return curve[i] + (curve[i + 1] - curve[i]) * f;
    }
}
''' % (DEMAT_TICKS, REMAT_TICKS, arr('DEMAT_ALPHA', demat), arr('DEMAT_LAMP', lamp_d), arr('REMAT_ALPHA', remat),
       arr('REMAT_LAMP', lamp_r))
    with open(OUT, 'w', newline='\r\n') as f:
        f.write(java)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
